let agendamentos = [];


/* =====================================
   DIAS DA SEMANA
===================================== */

const diasSemana = [
    "segunda",
    "terca",
    "quarta",
    "quinta",
    "sexta"
];


/* =====================================
   CONEXÃO COM NODE.JS
===================================== */

async function carregarDadosDoServidor() {

    try {

        const resposta = await fetch("/api/dados");

        if (!resposta.ok) {
            throw new Error("Erro ao carregar os dados.");
        }

        const dados = await resposta.json();


        if (
            dados.cardapios &&
            Object.keys(dados.cardapios).length > 0
        ) {

            cardapios = dados.cardapios;

        }


        if (Array.isArray(dados.agendamentos)) {

            agendamentos = dados.agendamentos;

        }


        console.log("Dados carregados do servidor!");

    } catch (erro) {

        console.error(
            "Erro ao carregar dados:",
            erro
        );

    }

}


/* =====================================
   SALVAR NO NODE.JS
===================================== */

async function salvarDadosNoServidor() {

    try {

        const resposta = await fetch(
            "/api/dados",
            {
                method: "POST",

                headers: {
                    "Content-Type": "application/json"
                },

                body: JSON.stringify({
                    cardapios: cardapios,
                    agendamentos: agendamentos
                })
            }
        );


        if (!resposta.ok) {
            throw new Error("Erro ao salvar os dados.");
        }


        console.log("Dados salvos no servidor!");

    } catch (erro) {

        console.error(
            "Erro ao salvar:",
            erro
        );

    }

}


/* =====================================
   VERIFICAR CONTRA TURNO
===================================== */

function ehContraTurno(alimentos) {

    return alimentos.some(function (alimento) {

        return alimento.startsWith(
            "Contra turno:"
        );

    });

}


